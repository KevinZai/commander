#!/usr/bin/env node
'use strict';

var fs = require('fs');
var path = require('path');

// BUMP_VERSION_ROOT lets tests run the script against a temp copy of the
// manifests instead of the real checkout (see #209: the old test rewrote the
// real marketplace.json while parallel tests were reading it).
var ROOT = process.env.BUMP_VERSION_ROOT
  ? path.resolve(process.env.BUMP_VERSION_ROOT)
  : path.join(__dirname, '..');

var version = process.argv[2];
if (!version) {
  process.stderr.write('Usage: node scripts/bump-version.js <version>\n');
  process.stderr.write('Example: node scripts/bump-version.js 4.0.1\n');
  process.exit(1);
}

// Strict semver, X.Y.Z with an optional pre-release (Codex #302 M10). The version is written into
// install-remote.sh's CCC_SHIPPED_REF="v<version>" shell assignment and names the release tag, so nothing
// else gets through: no shell characters, and no +build metadata, which install-remote.sh refuses as a ref.
var NUM = '(?:0|[1-9]\\d*)';
var PRE_ID = '(?:0|[1-9]\\d*|\\d*[A-Za-z-][0-9A-Za-z-]*)';
var STRICT_SEMVER = new RegExp('^' + NUM + '\\.' + NUM + '\\.' + NUM + '(?:-' + PRE_ID + '(?:\\.' + PRE_ID + ')*)?$');
if (!STRICT_SEMVER.test(version)) {
  process.stderr.write('ERROR: version must be strict semver X.Y.Z or X.Y.Z-prerelease (got: ' + JSON.stringify(version) + ')\n');
  if (version.indexOf('+') !== -1) process.stderr.write('  Build metadata (+...) is not supported: release tags and install-remote.sh refs cannot carry it.\n');
  process.exit(1);
}

var MANIFESTS = [
  path.join(ROOT, 'package.json'),
  path.join(ROOT, 'commander', 'cowork-plugin', '.claude-plugin', 'plugin.json'),
  path.join(ROOT, '.claude-plugin', 'marketplace.json'),
  path.join(ROOT, '.agents', 'plugins', 'marketplace.json'),
  path.join(ROOT, 'commander', 'contract.json'),
  // Generated by `npm run build:codex` from commander/cowork-plugin's
  // plugin.json — but it's a COMMITTED file (not gitignored), so it drifts
  // silently if bump-version.js skips it and nobody remembers to rebuild.
  // Bumping the version field directly here keeps it in sync between
  // rebuilds; the next `npm run build:codex` will re-derive it anyway.
  path.join(ROOT, 'commander', 'cowork-plugin-codex', '.codex-plugin', 'plugin.json'),
  path.join(ROOT, 'apps', 'mcp-server-cloud', 'package.json'),
];

// Also update lockfile version fields (top-level + packages[""] entry).
// The ROOT lockfile was missing here until 7.3.1 and had silently shipped a
// release behind; check-version-parity.js now asserts both of its fields.
var LOCKFILES = [
  path.join(ROOT, 'package-lock.json'),
  path.join(ROOT, 'apps', 'mcp-server-cloud', 'package-lock.json'),
];

// ATOMIC TWO-PHASE UPDATE:
// Phase 1 — read + parse + mutate all files into an in-memory plan.
//           Abort before ANY write if any parse/transform fails.
// Phase 2 — write each target to a temp file + rename(). rename() is
//           atomic on the same filesystem, so each manifest either
//           flips to the new version or stays at the old one.
// Best-effort rollback: if a rename fails mid-phase-2, restore files
// that were already renamed from their saved pre-image.

// Text files that pin the release tag: the remote installer's default ref and
// the tag-pinned download URL in its header and the beginner guide.
var TEXT_FILES = [
  { path: path.join(ROOT, 'install-remote.sh'), patterns: [/^(CCC_SHIPPED_REF="v)[^"]+(")$/m, /(\/commander\/v)\d+\.\d+\.\d+[^/]*(\/install-remote\.sh)/g] },
  { path: path.join(ROOT, 'guides', 'quickstart-beginner.md'), patterns: [/(\/commander\/v)\d+\.\d+\.\d+[^/]*(\/install-remote\.sh)/g] },
];

var plan = [];      // { path, beforeBytes, afterBytes, tempPath, summary[], mode }
var errors = [];

function buildPlan() {
  for (var manifestPath of MANIFESTS) {
    var raw = fs.readFileSync(manifestPath, 'utf8');
    var obj = JSON.parse(raw);
    var prev = obj.version;
    obj.version = version;

    // marketplace.json carries TWO version fields:
    //   - top-level `version` (the marketplace's version)
    //   - `plugins[i].version` (the published version for each plugin entry)
    // Desktop's Plugin UI reads plugins[i].version, NOT the top-level.
    // Must bump both or the Update button shows stale versions.
    var summary = [manifestPath.replace(ROOT + '/', '') + ' (' + prev + ' -> ' + version + ')'];
    if (Array.isArray(obj.plugins)) {
      for (var i = 0; i < obj.plugins.length; i++) {
        var p = obj.plugins[i];
        if (p && typeof p.version === 'string') {
          var pluginPrev = p.version;
          p.version = version;
          summary.push('  plugins[' + i + '](' + (p.name || '?') + '): ' + pluginPrev + ' -> ' + version);
        }
      }
    }

    plan.push({
      path: manifestPath,
      beforeBytes: raw,
      afterBytes: JSON.stringify(obj, null, 2) + '\n',
      tempPath: manifestPath + '.bump-tmp',
      summary: summary,
    });
  }

  // Each lockfile has version in two places: top-level + packages[""].version
  LOCKFILES.forEach(function (lockfile) {
    var lockRaw = fs.readFileSync(lockfile, 'utf8');
    var lock = JSON.parse(lockRaw);
    var lockPrev = lock.version;
    lock.version = version;
    if (lock.packages && lock.packages['']) {
      lock.packages[''].version = version;
    }
    plan.push({
      path: lockfile,
      beforeBytes: lockRaw,
      afterBytes: JSON.stringify(lock, null, 2) + '\n',
      tempPath: lockfile + '.bump-tmp',
      summary: [path.relative(ROOT, lockfile) + ' (' + lockPrev + ' -> ' + version + ')'],
    });
  });

  TEXT_FILES.forEach(function (file) {
    var textRaw = fs.readFileSync(file.path, 'utf8');
    var next = textRaw;
    file.patterns.forEach(function (re) { next = next.replace(re, '$1' + version + '$2'); });
    plan.push({
      path: file.path,
      beforeBytes: textRaw,
      afterBytes: next,
      tempPath: file.path + '.bump-tmp',
      summary: [path.relative(ROOT, file.path) + ' (release tag -> v' + version + ')'],
      mode: fs.statSync(file.path).mode & 0o777,
    });
  });
}

try {
  buildPlan();
} catch (err) {
  process.stderr.write('ABORT (phase 1 — parse/transform failed before any write):\n');
  process.stderr.write('  ' + err.message + '\n');
  process.exit(1);
}

// Phase 2 — write temp files first, then rename atomically.
// Track renamed files so we can roll back on any subsequent failure.
var renamed = [];
try {
  // First, write ALL temp files. If any write fails, nothing has moved yet.
  for (var item of plan) {
    fs.writeFileSync(item.tempPath, item.afterBytes, 'utf8');
    if (item.mode) fs.chmodSync(item.tempPath, item.mode);
  }
  // Then rename each into place. Each rename is atomic on the same fs.
  for (var item2 of plan) {
    fs.renameSync(item2.tempPath, item2.path);
    renamed.push(item2);
  }
} catch (err) {
  errors.push(err.message);
  // Rollback: restore every already-renamed file from the saved pre-image.
  for (var r of renamed) {
    try {
      fs.writeFileSync(r.path, r.beforeBytes, 'utf8');
    } catch (rErr) {
      errors.push('rollback failed for ' + r.path + ': ' + rErr.message);
    }
  }
  // Clean up any stray temp files from items not yet renamed.
  for (var p of plan) {
    if (fs.existsSync(p.tempPath)) {
      try { fs.unlinkSync(p.tempPath); } catch {}
    }
  }
  process.stderr.write('ABORT (phase 2 — write/rename failed; rolled back):\n');
  errors.forEach(function (e) { process.stderr.write('  ' + e + '\n'); });
  process.exit(1);
}

process.stdout.write('Bumped to ' + version + ':\n');
plan.forEach(function (item) {
  item.summary.forEach(function (s) { process.stdout.write('  ' + s + '\n'); });
});
process.exit(0);
