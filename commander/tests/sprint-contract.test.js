'use strict';

// Sprint contract (lib/sprint-contract.mjs + scripts/sprint-contract.mjs): the
// acceptance-criteria file /ccc-plan writes, /ccc-build builds against and the
// verifier agent checks before /ccc-build or /ccc-ship call work done.

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync, execFileSync } = require('node:child_process');

const PLUGIN = path.join(__dirname, '..', 'cowork-plugin');
const SCRIPT = path.join(PLUGIN, 'scripts', 'sprint-contract.mjs');
const libP = import(path.join(PLUGIN, 'lib', 'sprint-contract.mjs'));

const PLAN = [
  '<!-- generated by /ccc-plan · 2026-11-18T00:00:00Z -->',
  '# Dark mode toggle',
  '',
  '## Evals — what does done look like?',
  '',
  '- [ ] Toggle persists across reloads — check: `npm test -- toggle`',
  '- [ ] Settings page renders the toggle `npm run build`',
  '- [ ] Default follows the system preference — check: manual — switch the OS theme and reload',
  '',
  '## Evals — what does broken look like?',
  '',
  '- The page flickers on load',
  '',
].join('\n');

function tmpRepo() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'ccc-contract-'));
  execFileSync('git', ['init', '-q'], { cwd: dir });
  execFileSync('git', ['-c', 'user.email=t@example.com', '-c', 'user.name=t', 'commit', '-q', '--allow-empty', '-m', 'init'], { cwd: dir });
  return dir;
}

function run(cwd, args, input) {
  const r = spawnSync(process.execPath, [SCRIPT, ...args], { cwd, input, encoding: 'utf8' });
  return { code: r.status, json: JSON.parse(r.stdout), stderr: r.stderr };
}

test('criteriaFromPlan reads the done-evals section and its check commands', async () => {
  const lib = await libP;
  const c = lib.criteriaFromPlan(PLAN);
  assert.deepStrictEqual(c.map((x) => x.id), ['AC1', 'AC2', 'AC3']);
  assert.strictEqual(c[0].text, 'Toggle persists across reloads');
  assert.strictEqual(c[0].check, 'npm test -- toggle');
  assert.strictEqual(c[1].check, 'npm run build');
  assert.strictEqual(c[2].check, null);
  assert.strictEqual(c[2].text, 'Default follows the system preference (observe: switch the OS theme and reload)');
  assert.strictEqual(lib.titleFromPlan(PLAN), 'Dark mode toggle');
});

test('rendered contract round-trips through parse and validates', async () => {
  const lib = await libP;
  const md = lib.renderContract({ title: 'Dark mode toggle', source: 'plan.md', criteria: lib.criteriaFromPlan(PLAN) });
  const parsed = lib.parseContract(md);
  assert.strictEqual(parsed.marker, true);
  assert.strictEqual(parsed.status, 'open');
  assert.strictEqual(parsed.criteria.length, 3);
  assert.strictEqual(parsed.criteria[0].check, 'npm test -- toggle');
  assert.strictEqual(parsed.criteria[2].check, null);
  assert.match(parsed.criteria[2].text, /\(observe: switch the OS theme and reload\)$/);
  const v = lib.validateContract(parsed);
  assert.strictEqual(v.ok, true, v.errors.join('; '));
  assert.strictEqual(v.warnings.length, 1, 'AC3 has no check command');
});

test('validateContract rejects an empty or unmarked contract', async () => {
  const lib = await libP;
  const v = lib.validateContract(lib.parseContract('# Sprint contract — x\n\nStatus: open\n\n## Acceptance criteria\n\n'));
  assert.strictEqual(v.ok, false);
  assert.ok(v.errors.some((e) => /marker/.test(e)));
  assert.ok(v.errors.some((e) => /no acceptance criteria/.test(e)));
});

test('normalizeVerdict: PASS only when every criterion passes with evidence', async () => {
  const lib = await libP;
  const parsed = lib.parseContract(lib.renderContract({ title: 'T', criteria: lib.criteriaFromPlan(PLAN) }));
  const all = { verdict: 'PASS', criteria: ['AC1', 'AC2', 'AC3'].map((id) => ({ id, status: 'pass', evidence: `${id} ok` })) };
  assert.strictEqual(lib.normalizeVerdict(parsed, all).verdict, 'PASS');
  const missing = { verdict: 'PASS', criteria: all.criteria.slice(0, 2) };
  const n = lib.normalizeVerdict(parsed, missing);
  assert.strictEqual(n.verdict, 'FAIL', 'a claimed PASS with a missing criterion is a FAIL');
  assert.strictEqual(n.results[2].status, 'unverified');
  const noEvidence = { verdict: 'PASS', criteria: all.criteria.map((c) => ({ ...c, evidence: '' })) };
  assert.strictEqual(lib.normalizeVerdict(parsed, noEvidence).verdict, 'FAIL');
  assert.strictEqual(lib.normalizeVerdict(parsed, null).verdict, 'FAIL');
});

test('CLI: from-plan, record, status, and archive on a new contract', () => {
  const dir = tmpRepo();
  fs.writeFileSync(path.join(dir, 'plan.md'), PLAN);
  const made = run(dir, ['from-plan', 'plan.md']);
  assert.strictEqual(made.code, 0, made.stderr);
  assert.strictEqual(made.json.criteria.length, 3);
  assert.ok(fs.existsSync(path.join(dir, 'tasks', 'sprint-contract.md')));
  const fingerprint = made.json.fingerprint;
  assert.match(fingerprint, /^[0-9a-f]{16}$/);
  const head = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: dir, encoding: 'utf8' }).trim();
  const bind = { fingerprint, head };

  const failing = run(dir, ['record', '-'], JSON.stringify({ ...bind, verdict: 'PASS', criteria: [{ id: 'AC1', status: 'pass', evidence: 'exit 0' }] }));
  assert.strictEqual(failing.code, 2, 'FAIL exits 2');
  assert.strictEqual(failing.json.verdict, 'FAIL');
  let text = fs.readFileSync(path.join(dir, 'tasks', 'sprint-contract.md'), 'utf8');
  assert.match(text, /^Status: failed$/m);
  assert.match(text, /- \[x\] AC1/);
  assert.match(text, /- \[ \] AC2/);

  const passing = run(dir, ['record', '-'], 'verifier says:\n' + JSON.stringify({ ...bind, verdict: 'PASS', criteria: ['AC1', 'AC2', 'AC3'].map((id) => ({ id, status: 'pass', evidence: 'ok' })) }));
  assert.strictEqual(passing.code, 0);
  text = fs.readFileSync(path.join(dir, 'tasks', 'sprint-contract.md'), 'utf8');
  assert.match(text, /^Status: verified$/m);
  assert.strictEqual((text.match(/^### /gm) || []).length, 2, 'two log entries');

  const status = run(dir, ['status']);
  assert.strictEqual(status.json.status, 'verified');
  assert.strictEqual(status.json.current, false, 'untracked plan.md makes the tree dirty');
  fs.rmSync(path.join(dir, 'plan.md'));
  assert.strictEqual(run(dir, ['status']).json.current, true);

  const next = run(dir, ['new', '--title', 'Second piece', '--criterion', 'The second thing works :: true']);
  assert.strictEqual(next.code, 0, JSON.stringify(next.json));
  assert.match(next.json.archived, /^tasks\/contracts\/\d{8}-dark-mode-toggle\.md$/);
  assert.ok(fs.existsSync(path.join(dir, next.json.archived)));
  assert.strictEqual(run(dir, ['validate']).code, 0);
});

