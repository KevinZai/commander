test('malformed check-json fails validation instead of becoming manual', async () => {
  const lib = await libP;
  const md = lib.renderContract({ title: 'Bad', criteria: [{ text: 'criterion text here', check: 'x\ny' }] })
    .replace(/check-json: `"x\\ny"`/, 'check-json: `"x\\ny`');
  const parsed = lib.parseContract(md);
  assert.strictEqual(parsed.criteria[0].check, null);
  const v = lib.validateContract(parsed);
  assert.strictEqual(v.ok, false);
  assert.match(v.errors.join(' '), /AC1: check-json/);
});

test('an empty or undecodable check-json is a hard error in validate and from-plan', async () => {
  const lib = await libP;
  const bare = lib.renderContract({ title: 'Bare', criteria: [{ text: 'criterion text here', check: 'true' }] })
    .replace(/· check: `true`/, '· check-json:');
  const v = lib.validateContract(lib.parseContract(bare));
  assert.strictEqual(v.ok, false);
  assert.match(v.errors.join(' '), /AC1: check-json/);
  assert.throws(() => lib.renderContract({ title: 'X', criteria: [{ text: 'criterion text here', check: null, checkError: 'bad' }] }), /undecodable/);
  const dir = tmpRepo();
  for (const line of ['- Works well enough · check-json: `"unterminated`', '- Works well enough · check-json:']) {
    fs.writeFileSync(path.join(dir, 'plan.md'), `# P\n\n## Acceptance criteria\n\n${line}\n`);
    const r = run(dir, ['from-plan', 'plan.md']);
    assert.strictEqual(r.code, 1, line);
    assert.match(r.json.errors.join(' '), /AC1: check-json/);
    assert.ok(!fs.existsSync(path.join(dir, 'tasks', 'sprint-contract.md')), 'nothing written');
  }
});

test('check-json with no space after the colon is still decoded (and rejected when malformed)', async () => {
  const lib = await libP;
  assert.match(lib.splitCriterion('Works well · check-json:not-json').checkError || '', /check-json/);
  assert.strictEqual(lib.splitCriterion('Works well · check-json:`"echo hi"`').check, 'echo hi');
});

test('CLI: breaking a verified criterion makes status not current and record refuse', () => {
  const dir = tmpRepo();
  const made = run(dir, ['new', '--title', 'Gate', '--criterion', 'A manual thing is checked :: manual']);
  assert.strictEqual(made.code, 0, JSON.stringify(made.json));
  const head = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: dir, encoding: 'utf8' }).trim();
  const report = (fp) => JSON.stringify({ fingerprint: fp, head, verdict: 'PASS', criteria: [{ id: 'AC1', status: 'pass', evidence: 'looked' }] });
  assert.strictEqual(run(dir, ['record', '-'], report(made.json.fingerprint)).code, 0);
  assert.strictEqual(run(dir, ['status']).json.current, true);
  const p = path.join(dir, 'tasks', 'sprint-contract.md');
  fs.writeFileSync(p, fs.readFileSync(p, 'utf8').replace('· check: `manual`', '· check-json:'));
  const st = run(dir, ['status']);
  assert.strictEqual(st.json.current, false);
  assert.strictEqual(st.json.valid, false);
  assert.notStrictEqual(st.json.fingerprint, made.json.fingerprint, 'raw criterion text is fingerprinted');
  const rec = run(dir, ['record', '-'], report(made.json.fingerprint));
  assert.strictEqual(rec.code, 1);
  assert.match(rec.json.errors.join(' '), /AC1: check-json/);
});

// CC-2188: a criterion that quotes the marker syntax inside a code span keeps its real check.
test('a check marker quoted inside a code span does not drop the real check (round trip)', async () => {
  const lib = await libP;
  assert.strictEqual(lib.splitCriterion('The preview displays `mode · check:manual` · check: `npm test`').check, 'npm test');
  assert.strictEqual(lib.splitCriterion('Shows ``a · check: `b` `` · check: `npm test`').check, 'npm test');
  const dir = tmpRepo();
  const made = run(dir, ['new', '--title', 'Quoted marker', '--criterion', 'The preview displays `mode · check:manual` :: npm test']);
  assert.strictEqual(made.code, 0, JSON.stringify(made.json));
  const parsed = lib.parseContract(fs.readFileSync(path.join(dir, 'tasks', 'sprint-contract.md'), 'utf8'));
  assert.strictEqual(parsed.criteria[0].check, 'npm test');
  assert.match(parsed.criteria[0].text, /`mode · check:manual`/);
});
